// ── Main ──────────────────────────────────────────────────────────────────────

function run() {
  if (!fs.existsSync(PILLARS_DIR)) {
    console.error(`✗ data/pillars/ not found — run pipeline-pillar.js first`);
    process.exit(1);
  }

  let files = fs.readdirSync(PILLARS_DIR)
    .filter(f => f.endsWith('.json'));

  if (SLUG_FILTER) {
    files = files.filter(f => f === `${SLUG_FILTER}.json`);
    if (files.length === 0) {
      console.error(`✗ No pillar JSON found for slug: ${SLUG_FILTER}`);
      process.exit(1);
    }
  }

  console.log(`\npipeline-pillar-render.js`);
  console.log(`Pillars: ${files.length}`);
  console.log(`${'─'.repeat(52)}`);

  let passed = 0;
  let failed = 0;

  for (const file of files) {
    const slug     = file.replace('.json', '');
    const jsonPath = path.join(PILLARS_DIR, file);
    const outPath  = path.join(OUTPUT_DIR, `${slug}.html`);

    try {
      const data = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
      const html = renderHTML(data);

      if (!DRY_RUN) {
        fs.writeFileSync(outPath, html, 'utf8');
      }

      console.log(`  ✓  ${slug}.html${DRY_RUN ? ' [DRY]' : ''}`);
      passed++;
    } catch (e) {
      console.error(`  ✗  ${slug}: ${e.message}`);
      failed++;
    }
  }

  console.log(`${'─'.repeat(52)}`);
  console.log(`  Passed: ${passed}`);
  console.log(`  Failed: ${failed}`);

  if (DRY_RUN) {
    console.log(`\n[DRY RUN] No files written.`);
  } else {
    console.log(`\nNext step: Open in browser to review, then git add . && git commit && git push`);
  }
}

run();
