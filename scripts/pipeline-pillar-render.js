#!/usr/bin/env node

/**
 * pipeline-pillar-render.js
 * BooksVersusMovies.com — Renders pillar JSON files to HTML
 *
 * Reads data/pillars/<slug>.json and outputs <slug>.html to project root.
 * Matches site CSS conventions from style.css — no inline styles needed.
 *
 * Usage:
 *   node scripts/pipeline-pillar-render.js                        (all pillars)
 *   node scripts/pipeline-pillar-render.js --slug should-you-read-the-book-first
 *   node scripts/pipeline-pillar-render.js --dry
 *
 * Destination: scripts/pipeline-pillar-render.js
 */

'use strict';

const fs   = require('fs');
const path = require('path');

// ── Args ──────────────────────────────────────────────────────────────────────

const args    = process.argv.slice(2);
const getArg  = flag => { const i = args.indexOf(flag); return i !== -1 && args[i+1] ? args[i+1] : null; };
const hasFlag = flag => args.includes(flag);

const SLUG_FILTER = getArg('--slug');
const DRY_RUN     = hasFlag('--dry');

// ── Paths ─────────────────────────────────────────────────────────────────────

const ROOT        = path.resolve(__dirname, '..');
const PILLARS_DIR = path.join(ROOT, 'data', 'pillars');
const OUTPUT_DIR  = ROOT;

const GA_ID    = 'G-P0DY0XDWVV';
const SITE_URL = 'https://booksversusmovies.com';

// ── Nav ───────────────────────────────────────────────────────────────────────

function renderNav() {
  const navPath = path.join(ROOT, 'config', 'nav.json');
  if (!fs.existsSync(navPath)) {
    return `<a href="/">Home</a> &nbsp;&middot;&nbsp;
      <a href="/upcoming-adaptations">Upcoming</a> &nbsp;&middot;&nbsp;
      <a href="/featured">Featured</a> &nbsp;&middot;&nbsp;
      <a href="/auteurs">The Auteurs</a> &nbsp;&middot;&nbsp;
      <a href="/about">About</a>`;
  }
  const items = JSON.parse(fs.readFileSync(navPath, 'utf8')).items;
  return items
    .map((item, i) => {
      const dot = i < items.length - 1 ? ` &nbsp;&middot;&nbsp;` : '';
      return `<a href="${item.href}">${item.label}</a>${dot}`;
    })
    .join('\n      ');
}

// ── Helpers ───────────────────────────────────────────────────────────────────

const esc = s => (s || '').toString()
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function renderProse(prose) {
  return (prose || '')
    .split(/\n\n+/)
    .map(p => p.trim())
    .filter(Boolean)
    .map(p => `      <p>${p}</p>`)
    .join('\n');
}

function renderSectionNav(sections) {
  return sections
    .map(s => `        <a href="#${esc(s.id)}" class="pillar-nav-link">${esc(s.h2)}</a>`)
    .join('\n');
}

function renderSections(sections) {
  return sections.map(s => `
    <section class="pillar-section" id="${esc(s.id)}">
      <h2>${esc(s.h2)}</h2>
${renderProse(s.prose)}
    </section>`).join('\n');
}

